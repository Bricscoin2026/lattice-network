#!/bin/bash
# ============================================================================
#  Lattice Network · One-Click Installer
#  Versione 1.0 · Giugno 2026
#
#  Bootstrap completo su una VM Debian/Ubuntu fresca:
#    1. Verifica prerequisiti (Docker, openssl)
#    2. Genera segreti random crittograficamente sicuri (.env)
#    3. Costruisce certificati TLS self-signed (sostituibili con LE)
#    4. Avvia lo stack docker-compose (Mongo + Backend + 4 validator + 3 mixnet
#       + frontend nginx)
#    5. Configura cron per backup automatici orari
#    6. Stampa l'URL admin con la passphrase d'accesso iniziale
#
#  Uso:
#    sudo ./install.sh [--domain mycompany.lattice.local] [--mode compliance|whistleblowing]
#
#  Requisiti minimi:  Ubuntu 22.04+ · 4 vCPU · 8 GB RAM · 50 GB SSD
# ============================================================================
set -euo pipefail

DOMAIN="${LATTICE_DOMAIN:-lattice.local}"
MODE="${LATTICE_MODE:-compliance}"
INSTALL_DIR="${LATTICE_DIR:-/opt/lattice}"

while [[ $# -gt 0 ]]; do
  case "$1" in
    --domain) DOMAIN="$2"; shift 2;;
    --mode)   MODE="$2"; shift 2;;
    --dir)    INSTALL_DIR="$2"; shift 2;;
    *) echo "Uso: $0 [--domain DOMAIN] [--mode compliance|whistleblowing] [--dir /opt/lattice]"; exit 1;;
  esac
done

if [[ $EUID -ne 0 ]]; then
  echo "❌ Errore: questo script deve girare come root (sudo)."
  exit 1
fi

echo "════════════════════════════════════════════════════════════"
echo "  Lattice Network · Installer one-click"
echo "════════════════════════════════════════════════════════════"
echo "  Dominio:       $DOMAIN"
echo "  Modalità:      $MODE"
echo "  Directory:     $INSTALL_DIR"
echo

# ----- 1. Prerequisiti -----
echo "▸ [1/6] Verifico prerequisiti..."

# Docker: usa lo script ufficiale (apt 'docker' non esiste su Ubuntu)
if ! command -v docker &>/dev/null; then
  echo "  ❌ 'docker' non trovato. Installo via get.docker.com..."
  curl -fsSL https://get.docker.com | sh
fi

for cmd in openssl curl python3; do
  if ! command -v "$cmd" &>/dev/null; then
    echo "  ❌ '$cmd' non trovato. Installo..."
    apt-get update -qq && apt-get install -y -qq "$cmd"
  fi
done
if ! docker compose version &>/dev/null; then
  echo "  ❌ docker-compose v2 non trovato. Installo docker-compose-plugin..."
  apt-get install -y -qq docker-compose-plugin
fi
echo "  ✓ docker $(docker --version | awk '{print $3}' | tr -d ,)"
echo "  ✓ docker compose $(docker compose version --short)"
echo "  ✓ openssl $(openssl version | awk '{print $2}')"

# ----- 2. Segreti random -----
echo "▸ [2/6] Genero segreti crittografici..."
# Brace expansion NON funziona dentro virgolette: usa una loop esplicita
mkdir -p "$INSTALL_DIR"
for sub in data secrets backups certs logs; do
  mkdir -p "$INSTALL_DIR/$sub"
done
cd "$INSTALL_DIR"

gen_secret() { openssl rand -hex 32; }

if [[ ! -f .env ]]; then
  cat > .env <<EOF
# Lattice Network — generated by install.sh on $(date -u +%Y-%m-%dT%H:%M:%SZ)
LATTICE_DOMAIN=$DOMAIN
LATTICE_COMPLIANCE_MODE=$([[ "$MODE" == "compliance" ]] && echo 1 || echo 0)
LATTICE_STRICT_AUTH=1

MONGO_URL=mongodb://lattice:$(gen_secret)@mongo:27017/?authSource=admin
MONGO_INITDB_ROOT_USERNAME=lattice
MONGO_INITDB_ROOT_PASSWORD=$(gen_secret)
DB_NAME=lattice_prod

# JWT signing key (rotated every 90 days)
JWT_SECRET=$(gen_secret)

# AES-256-GCM at-rest encryption key (NEVER rotate without re-encrypting all data)
AT_REST_KEY=$(gen_secret)

# CORS — restrict to your domain in production
CORS_ORIGINS=https://$DOMAIN

# Operator initial passphrase — printed at end of install
SOVEREIGN_BOOTSTRAP_PASSPHRASE=$(openssl rand -base64 24)
EOF
  chmod 600 .env
  echo "  ✓ Generati 5 segreti random (.env, chmod 600)"
else
  echo "  ✓ .env già esistente, riuso"
fi

# ----- 3. TLS self-signed (sostituibile con Let's Encrypt) -----
echo "▸ [3/6] Genero certificati TLS self-signed..."
if [[ ! -f certs/server.crt ]]; then
  openssl req -x509 -nodes -days 365 -newkey rsa:4096 \
    -keyout certs/server.key -out certs/server.crt \
    -subj "/C=IT/O=Lattice/CN=$DOMAIN" \
    -addext "subjectAltName=DNS:$DOMAIN" 2>/dev/null
  chmod 600 certs/server.key
  echo "  ✓ Certificato self-signed creato (sostituiscilo con Let's Encrypt in produzione)"
else
  echo "  ✓ Certificato già presente"
fi

# ----- 4. Docker compose up -----
echo "▸ [4/6] Avvio stack docker-compose..."
if [[ ! -f docker-compose.yml ]]; then
  echo "  ❌ docker-compose.yml mancante. Copialo da /app/deploy/docker-compose.yml"
  exit 1
fi
docker compose pull
docker compose up -d
sleep 8

# ----- 5. Healthcheck -----
echo "▸ [5/6] Verifico healthcheck servizi..."
for service in mongo backend; do
  if docker compose ps "$service" | grep -q "Up\|healthy"; then
    echo "  ✓ $service: running"
  else
    echo "  ⚠ $service: NOT running. Vedi 'docker compose logs $service'"
  fi
done

# ----- 6. Backup cron -----
echo "▸ [6/6] Configuro backup automatici orari..."
cat > /etc/cron.hourly/lattice-backup <<'CRON'
#!/bin/bash
cd /opt/lattice
TS=$(date +%Y%m%d-%H%M%S)
curl -s -H "X-Lattice-Role: sovereign" \
  http://localhost:8001/api/admin/backup/snapshot \
  -o "backups/snap-$TS.json"
# Mantieni ultimi 168 backup (1 settimana orari)
ls -t backups/snap-*.json 2>/dev/null | tail -n +169 | xargs -r rm -f
CRON
chmod +x /etc/cron.hourly/lattice-backup
echo "  ✓ Backup orari abilitati in /etc/cron.hourly/lattice-backup"
echo "    Backup salvati in $INSTALL_DIR/backups/ (rotazione: ultimi 7 giorni)"

PASS=$(grep SOVEREIGN_BOOTSTRAP_PASSPHRASE .env | cut -d= -f2)
echo
echo "════════════════════════════════════════════════════════════"
echo "  ✅ INSTALLAZIONE COMPLETATA"
echo "════════════════════════════════════════════════════════════"
echo "  Console admin:    https://$DOMAIN"
echo "  Passphrase init:  $PASS"
echo "  Modalità:         $MODE"
echo
echo "  Prossimi passi:"
echo "    1. Apri https://$DOMAIN/onboarding nel browser"
echo "    2. Registra la tua prima azienda"
echo "    3. Scarica .keypair.json e custodiscilo"
echo "    4. Sostituisci il certificato self-signed con Let's Encrypt:"
echo "         certbot certonly --standalone -d $DOMAIN"
echo "         cp /etc/letsencrypt/live/$DOMAIN/fullchain.pem certs/server.crt"
echo "         cp /etc/letsencrypt/live/$DOMAIN/privkey.pem    certs/server.key"
echo "         docker compose restart frontend"
echo
echo "  Backup manuale on-demand:"
echo "    /etc/cron.hourly/lattice-backup"
echo
echo "  Documentazione: $INSTALL_DIR/README.md"
echo "════════════════════════════════════════════════════════════"
