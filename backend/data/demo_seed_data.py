def _demo_random_past_ts(max_days: int = 14) -> str:
    """Return ISO timestamp in the last `max_days` days, biased to business hours."""
    now = datetime.now(timezone.utc)
    days_back = random.randint(0, max_days)
    hour = random.choice([8, 9, 10, 10, 11, 11, 14, 14, 15, 16, 17, 17])
    minute = random.randint(0, 59)
    ts = now - timedelta(days=days_back, hours=now.hour - hour, minutes=now.minute - minute)
    return ts.replace(microsecond=0).isoformat()
