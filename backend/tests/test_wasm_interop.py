"""Cross-library WASM ↔ Python interop test.

Verifies that:
  1. A keypair generated by `pqcrypto.sign.ml_dsa_65` (Python) can be
     used by the Rust `ml-dsa` crate to produce a valid signature, and
     vice-versa.
  2. The pk/sk/sig byte lengths match (1952 / 4032 / 3309).

Run with:
    cd /app/backend && python3 tests/test_wasm_interop.py
"""
import sys
import subprocess
import json
from pathlib import Path

from pqcrypto.sign import ml_dsa_65 as mldsa

print("=" * 64)
print("ML-DSA-65 wire-format interop check")
print("=" * 64)

# 1) Generate with Python.
pk, sk = mldsa.generate_keypair()
msg = b"the quick brown fox jumps over the lazy dog"
sig = mldsa.sign(sk, msg)
print(f"  Python  pk={len(pk)}b · sk={len(sk)}b · sig={len(sig)}b")
assert len(pk) == 1952, f"pk size mismatch: {len(pk)}"
assert len(sk) == 4032, f"sk size mismatch: {len(sk)}"
assert len(sig) == 3309, f"sig size mismatch: {len(sig)}"
ok_self = mldsa.verify(pk, msg, sig)
print(f"  Python verify of its own sig: {ok_self}")

# 2) Use the Rust ml-dsa crate via a tiny native test binary on the host.
#    We compile a one-shot Rust binary that consumes the same pk/sk and
#    cross-signs / cross-verifies.
test_dir = Path("/tmp/lattice-mldsa-host-test")
test_dir.mkdir(exist_ok=True)
(test_dir / "Cargo.toml").write_text("""
[package]
name = "host_test"
version = "0.0.1"
edition = "2021"

[dependencies]
ml-dsa = { version = "0.1", default-features = false, features = ["alloc", "getrandom", "rand_core"] }
hex = "0.4"

[[bin]]
name = "host_test"
path = "main.rs"
""")
(test_dir / "main.rs").write_text("""
use std::io::Read;
use ml_dsa::{ExpandedSigningKey, ExpandedSigningKeyBytes, MlDsa65, Signature, VerifyingKey};
use ml_dsa::signature::{Signer, Verifier, SignatureEncoding};
use ml_dsa::common::{KeyExport, KeyInit};

fn main() {
    let mut input = String::new();
    std::io::stdin().read_to_string(&mut input).unwrap();
    let parts: Vec<&str> = input.trim().split('\\n').collect();
    let mode = parts[0];

    if mode == "sign" {
        let sk_hex = parts[1];
        let msg_hex = parts[2];
        let sk_bytes = hex::decode(sk_hex).unwrap();
        let sk_arr: &ExpandedSigningKeyBytes<MlDsa65> = sk_bytes.as_slice().try_into().unwrap();
        #[allow(deprecated)]
        let sk = ExpandedSigningKey::<MlDsa65>::from_expanded(sk_arr);
        let msg = hex::decode(msg_hex).unwrap();
        let sig: Signature<MlDsa65> = sk.sign(&msg);
        println!("{}", hex::encode(sig.to_bytes()));
    } else if mode == "verify" {
        let pk_hex = parts[1];
        let msg_hex = parts[2];
        let sig_hex = parts[3];
        let pk_bytes = hex::decode(pk_hex).unwrap();
        let pk = VerifyingKey::<MlDsa65>::new_from_slice(&pk_bytes).unwrap();
        let msg = hex::decode(msg_hex).unwrap();
        let sig_bytes = hex::decode(sig_hex).unwrap();
        match Signature::<MlDsa65>::try_from(sig_bytes.as_slice()) {
            Ok(sig) => println!("{}", pk.verify(&msg, &sig).is_ok()),
            Err(_) => println!("false"),
        }
    }
}
""")

print("\n  Building host-side Rust ml-dsa binary (one-time, ~30s)...")
build = subprocess.run(
    ["cargo", "build", "--release", "--quiet"],
    cwd=test_dir, env={**__import__('os').environ, "PATH": f"{__import__('os').environ['HOME']}/.cargo/bin:{__import__('os').environ.get('PATH','')}"},
    capture_output=True, text=True, timeout=120,
)
if build.returncode != 0:
    print("  Build failed:", build.stderr[-800:])
    sys.exit(1)

binary = test_dir / "target" / "release" / "host_test"

# Cross-verify: Rust signs with Python-generated sk, Python verifies.
inp = f"sign\n{sk.hex()}\n{msg.hex()}\n"
rust_sig_hex = subprocess.run([str(binary)], input=inp, capture_output=True, text=True).stdout.strip()
print(f"  Rust signed (using Python's sk): sig={len(rust_sig_hex)//2}b")
assert len(rust_sig_hex) == 3309 * 2, f"Rust sig wrong length: {len(rust_sig_hex)//2}"
ok_x1 = mldsa.verify(pk, msg, bytes.fromhex(rust_sig_hex))
print(f"  Python verifies Rust-signed sig: {ok_x1}")

# Cross-verify the other way: Rust verifies Python's signature.
inp = f"verify\n{pk.hex()}\n{msg.hex()}\n{sig.hex()}\n"
ok_x2 = subprocess.run([str(binary)], input=inp, capture_output=True, text=True).stdout.strip()
print(f"  Rust verifies Python-signed sig: {ok_x2}")

print()
if ok_x1 and ok_x2 == "true":
    print("  RESULT: ✅ Wire-format compatibility CONFIRMED")
    print("  The Rust WASM module and the Python backend can sign/verify")
    print("  each other's messages byte-for-byte. ML-DSA-65 = ML-DSA-65.")
    sys.exit(0)
else:
    print("  RESULT: ❌ Wire-format mismatch — DO NOT ship to production")
    sys.exit(2)
